# Код для расчета времени года по номеру месяцв

x = int(input("Введите номер месяца: "))
if x == 12 or 1 <= x <= 2:
    print("Текущее время года - Зима")
elif 2 < x <= 5:
    print("Текущее время года - Весна")
elif 5 < x <= 8:
    print("Текущее время года - Лето")
elif 8 < x <= 11:
    print("Текущее время года - Осень")
else:
    print("Неккоректно набран номер")
